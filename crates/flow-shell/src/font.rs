//! The terminal's bitmap font, so text can be painted with no dependency at all.
//!
//! **Why a font lives here rather than in an image library.** The shell's terminal has to
//! *show* the characters a person types, and this crate's whole reason for existing is
//! that it links against nothing a stock macOS has. A font file would need a parser; a
//! system font would need a font engine. A 5×7 bitmap is data, and data compiles.
//!
//! **The glyphs** are the classic public-domain 5×7 bitmap font, one byte per column and
//! five columns per glyph, with bit 0 the top row. `FONT` is ordered from ASCII 0x20
//! (space) to 0x7E (tilde). A character outside that range has no glyph here and is drawn
//! as nothing; the terminal still *holds* it, so text is never silently dropped.
//!
//! The shape a glyph is drawn with is asserted in `tests/input.rs` — a glyph that draws
//! no pixels would make "the text appeared" read as true while nothing changed, which is
//! exactly the false pass this repository is written against.

use crate::GLYPH_W;

/// One glyph: five bytes, one per column, bit 0 the top row.
///
/// Kept as a `[u8; 5]` so a caller indexes columns by position rather than by bit math.
pub(crate) fn glyph(ch: char) -> [u8; GLYPH_W as usize] {
    let c = ch as u32;
    let Some(offset) = c.checked_sub(0x20) else {
        return [0; GLYPH_W as usize];
    };
    if offset >= 95 {
        return [0; GLYPH_W as usize];
    }
    let base = offset as usize * 5;
    let mut out = [0; GLYPH_W as usize];
    out.copy_from_slice(&FONT[base..base + 5]);
    out
}

